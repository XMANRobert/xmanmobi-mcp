CREATE TABLE IF NOT EXISTS `ad_ai_action_proposals` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `proposal_key` CHAR(43) NOT NULL,
  `user_id` BIGINT UNSIGNED NOT NULL,
  `platform` VARCHAR(20) NOT NULL,
  `customer_id` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `account_id` BIGINT UNSIGNED NOT NULL,
  `resource_type` VARCHAR(30) NOT NULL,
  `resource_id` BIGINT UNSIGNED NOT NULL,
  `remote_id` VARCHAR(100) NOT NULL DEFAULT '',
  `action_type` VARCHAR(40) NOT NULL,
  `old_value` TEXT NOT NULL,
  `new_value` TEXT NOT NULL,
  `reason` VARCHAR(1000) NOT NULL DEFAULT '',
  `evidence_json` LONGTEXT NULL,
  `risk_level` VARCHAR(20) NOT NULL,
  `status` VARCHAR(20) NOT NULL DEFAULT 'proposed',
  `confirmation_token_hash` CHAR(64) NOT NULL,
  `idempotency_key` VARCHAR(100) NOT NULL,
  `expires_at` DATETIME NOT NULL,
  `executed_at` DATETIME NULL,
  `created_at` DATETIME NOT NULL,
  `updated_at` DATETIME NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_proposal_key` (`proposal_key`),
  UNIQUE KEY `uk_idempotency_key` (`idempotency_key`),
  KEY `idx_user_status` (`user_id`, `status`),
  KEY `idx_resource` (`platform`, `resource_type`, `resource_id`),
  KEY `idx_expires_at` (`expires_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `ad_ai_action_audit_logs` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `proposal_id` BIGINT UNSIGNED NOT NULL,
  `user_id` BIGINT UNSIGNED NOT NULL,
  `platform` VARCHAR(20) NOT NULL,
  `customer_id` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `account_id` BIGINT UNSIGNED NOT NULL,
  `resource_type` VARCHAR(30) NOT NULL,
  `resource_id` BIGINT UNSIGNED NOT NULL,
  `remote_id` VARCHAR(100) NOT NULL DEFAULT '',
  `action_type` VARCHAR(40) NOT NULL,
  `phase` VARCHAR(20) NOT NULL,
  `before_json` LONGTEXT NULL,
  `after_json` LONGTEXT NULL,
  `request_json` LONGTEXT NULL,
  `response_json` LONGTEXT NULL,
  `status` VARCHAR(20) NOT NULL,
  `error_message` TEXT NULL,
  `ip_address` VARCHAR(64) NOT NULL DEFAULT '',
  `user_agent` VARCHAR(500) NOT NULL DEFAULT '',
  `created_at` DATETIME NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_proposal` (`proposal_id`),
  KEY `idx_user_created` (`user_id`, `created_at`),
  KEY `idx_resource_created` (`platform`, `resource_type`, `resource_id`, `created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
